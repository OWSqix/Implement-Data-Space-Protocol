#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Parser, Store, Writer } from "n3";
import {
  loadProfileRelease,
  profileVersionEnvironmentVariable,
  resolveProfileVersion,
  resolveReleaseArtifact,
  selectProfileBundle,
} from "../../src/profile/registry.mjs";

function failure(code, message, details = {}) {
  const error = new Error(message);
  error.code = code;
  error.details = details;
  return error;
}

function usage() {
  return [
    "Usage:",
    "  node tools/profile/build-bundles.mjs [--version VERSION]",
    "",
    `If --version is omitted, ${profileVersionEnvironmentVariable} selects the release.`,
  ].join("\n");
}

export function parseBuildArguments(argv) {
  let version;
  for (let index = 0; index < argv.length; index += 2) {
    const flag = argv[index];
    const value = argv[index + 1];
    if (flag !== "--version"
      || value === undefined
      || value.startsWith("--")
      || version !== undefined) {
      throw failure("INVALID_ARGUMENTS", `invalid bundle build arguments\n${usage()}`);
    }
    version = value;
  }
  return { version };
}

function blankNodeComponent(value) {
  return value.replace(/[^0-9A-Za-z_]/gu, "_");
}

async function serializeTurtleSources(release, sources, blankNodePrefix) {
  const store = new Store();
  for (const [index, relativePath] of sources.entries()) {
    const parser = new Parser({
      blankNodePrefix: `_:${blankNodePrefix}_${String(index).padStart(2, "0")}_`,
      format: "text/turtle",
    });
    store.addQuads(parser.parse(await readFile(
      resolveReleaseArtifact(release, relativePath),
      "utf8",
    )));
  }
  const writer = new Writer({ format: "text/turtle" });
  writer.addQuads(store.getQuads(null, null, null, null));
  return new Promise((resolve, reject) => {
    writer.end((error, result) => (error ? reject(error) : resolve(result)));
  });
}

export function profileBundleBuildDefinitions(release) {
  const definitions = Object.entries(release.manifest.profiles)
    .filter(([, profile]) => (
      profile.bundle !== undefined || profile.kind === "conformance"
    ))
    .map(([profileName, profile]) => ({
      bundle: selectProfileBundle(release, profile, profileName),
      profileName,
      sources: profile.shapes,
    }))
    .sort((left, right) => (
      left.profileName < right.profileName ? -1 : left.profileName > right.profileName ? 1 : 0
    ));
  const duplicateBundleNames = definitions
    .map((definition) => definition.bundle.name)
    .filter((name, index, names) => names.indexOf(name) !== index);
  if (duplicateBundleNames.length > 0) {
    throw failure(
      "DUPLICATE_PROFILE_BUNDLE",
      "each bundled profile must publish a distinct bundle",
      { bundles: [...new Set(duplicateBundleNames)].sort() },
    );
  }
  const recursiveDefinitions = definitions
    .filter((definition) => definition.sources.includes(definition.bundle.path))
    .map((definition) => definition.profileName);
  if (recursiveDefinitions.length > 0) {
    throw failure(
      "RECURSIVE_PROFILE_BUNDLE",
      "a generated bundle cannot be one of its own shape sources",
      { profiles: recursiveDefinitions },
    );
  }
  return definitions;
}

export async function buildProfileBundles({ version: requestedVersion } = {}) {
  const version = resolveProfileVersion(requestedVersion);
  const release = await loadProfileRelease(version);
  const definitions = profileBundleBuildDefinitions(release);
  const outputs = [];

  for (const definition of definitions) {
    const turtle = await serializeTurtleSources(
      release,
      definition.sources,
      blankNodeComponent(definition.bundle.name),
    );
    const header = [
      "# Generated by tools/profile/build-bundles.mjs.",
      `# Validation bundle: ${definition.bundle.name}`,
      ...definition.sources.map((source) => `# Source: ${source}`),
      "",
    ].join("\n");
    const outputPath = resolveReleaseArtifact(release, definition.bundle.path);
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, `${header}${turtle}`, "utf8");
    outputs.push({
      bundle: definition.bundle.name,
      path: definition.bundle.path,
      profile: definition.profileName,
    });
  }

  const supportPath = release.manifest.publishedBundles.support;
  if (release.manifest.background.includes(supportPath)) {
    throw failure(
      "RECURSIVE_PROFILE_BUNDLE",
      "the generated support bundle cannot be one of its own sources",
      { path: supportPath },
    );
  }
  const supportTurtle = await serializeTurtleSources(
    release,
    release.manifest.background,
    "support",
  );
  const supportHeader = [
    "# Generated by tools/profile/build-bundles.mjs.",
    "# Validation support graph; merge with the input data graph before SHACL validation.",
    ...release.manifest.background.map((source) => `# Source: ${source}`),
    "",
  ].join("\n");
  const supportOutputPath = resolveReleaseArtifact(release, supportPath);
  await mkdir(path.dirname(supportOutputPath), { recursive: true });
  await writeFile(supportOutputPath, `${supportHeader}${supportTurtle}`, "utf8");
  outputs.push({ bundle: "support", path: supportPath, profile: null });

  return { outputs, profileVersion: version };
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : null;
if (invokedPath === fileURLToPath(import.meta.url)) {
  try {
    const options = parseBuildArguments(process.argv.slice(2));
    const result = await buildProfileBundles(options);
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`${JSON.stringify({
      code: error.code ?? "PROFILE_BUNDLE_BUILD_FAILED",
      details: error.details ?? {},
      message: error.message,
    }, null, 2)}\n`);
    process.exitCode = 1;
  }
}
