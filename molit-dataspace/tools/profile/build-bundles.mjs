#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Parser, Store, Writer } from "n3";

const projectRoot = path.resolve(fileURLToPath(new URL("../../", import.meta.url)));
const releaseRoot = path.join(
  projectRoot,
  "profiles",
  "molit-dcat-ap",
  "releases",
  "0.1.0",
);
const manifest = JSON.parse(await readFile(path.join(releaseRoot, "manifest.json"), "utf8"));
const bundleNames = Object.entries(manifest.profiles)
  .filter(([, profile]) => profile.kind === "conformance")
  .map(([name]) => name)
  .sort();
const outputRoot = path.join(releaseRoot, "bundles");
await mkdir(outputRoot, { recursive: true });

for (const bundleName of bundleNames) {
  const store = new Store();
  const sources = manifest.profiles[bundleName].shapes;
  for (const [index, relativePath] of sources.entries()) {
    const parser = new Parser({
      blankNodePrefix: `_:${bundleName}_${String(index).padStart(2, "0")}_`,
      format: "text/turtle",
    });
    store.addQuads(parser.parse(await readFile(path.join(releaseRoot, relativePath), "utf8")));
  }
  const writer = new Writer({ format: "text/turtle" });
  writer.addQuads(store.getQuads(null, null, null, null));
  const turtle = await new Promise((resolve, reject) => {
    writer.end((error, result) => (error ? reject(error) : resolve(result)));
  });
  const header = [
    "# Generated by tools/profile/build-bundles.mjs.",
    `# Validation bundle: ${bundleName}`,
    ...sources.map((source) => `# Source: ${source}`),
    "",
  ].join("\n");
  await writeFile(path.join(outputRoot, `${bundleName}.ttl`), `${header}${turtle}`, "utf8");
}

const supportStore = new Store();
for (const [index, relativePath] of manifest.background.entries()) {
  const parser = new Parser({
    blankNodePrefix: `_:support_${String(index).padStart(2, "0")}_`,
    format: "text/turtle",
  });
  supportStore.addQuads(parser.parse(await readFile(path.join(releaseRoot, relativePath), "utf8")));
}
const supportWriter = new Writer({ format: "text/turtle" });
supportWriter.addQuads(supportStore.getQuads(null, null, null, null));
const supportTurtle = await new Promise((resolve, reject) => {
  supportWriter.end((error, result) => (error ? reject(error) : resolve(result)));
});
const supportHeader = [
  "# Generated by tools/profile/build-bundles.mjs.",
  "# Validation support graph; merge with the input data graph before SHACL validation.",
  ...manifest.background.map((source) => `# Source: ${source}`),
  "",
].join("\n");
await writeFile(path.join(outputRoot, "support.ttl"), `${supportHeader}${supportTurtle}`, "utf8");
